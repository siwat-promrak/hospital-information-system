#!/usr/bin/env node
// Generates a deeply-typed `K` const from src/messages/en.json so call sites
// can write `t(K.Home.title)` instead of raw string literals.
//
// Leaf values are the leaf key itself (NOT the full dotted path), because
// `useTranslations("Home")` already scopes by namespace and expects "title".

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const WEB_ROOT = resolve(__dirname, "..");
const SOURCE_PATH = resolve(WEB_ROOT, "src/messages/en.json");
const OUTPUT_PATH = resolve(WEB_ROOT, "src/i18n/keys.generated.ts");

function isPlainObject(value) {
  return (
    typeof value === "object" &&
    value !== null &&
    !Array.isArray(value) &&
    Object.getPrototypeOf(value) === Object.prototype
  );
}

function sortedEntries(obj) {
  return Object.entries(obj).sort(([a], [b]) => a.localeCompare(b));
}

function escapeStringLiteral(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

let leafCount = 0;

function renderNode(node, indentLevel) {
  if (!isPlainObject(node)) {
    throw new Error(
      "Top-level messages must be a plain object of namespaces.",
    );
  }

  const indent = "  ".repeat(indentLevel);
  const innerIndent = "  ".repeat(indentLevel + 1);
  const entries = sortedEntries(node);

  if (entries.length === 0) {
    return "{}";
  }

  const lines = ["{"];

  for (const [key, value] of entries) {
    const safeKey = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key)
      ? key
      : `"${escapeStringLiteral(key)}"`;

    if (isPlainObject(value)) {
      const child = renderNode(value, indentLevel + 1);
      lines.push(`${innerIndent}${safeKey}: ${child},`);
    } else if (typeof value === "string") {
      leafCount += 1;
      lines.push(`${innerIndent}${safeKey}: "${escapeStringLiteral(key)}",`);
    } else {
      throw new Error(
        `Unsupported message value at key "${key}": expected string or object, got ${typeof value}.`,
      );
    }
  }

  lines.push(`${indent}}`);

  return lines.join("\n");
}

async function main() {
  let raw;

  try {
    raw = await readFile(SOURCE_PATH, "utf8");
  } catch (err) {
    throw new Error(`Failed to read ${SOURCE_PATH}: ${err.message}`);
  }

  let messages;

  try {
    messages = JSON.parse(raw);
  } catch (err) {
    throw new Error(`Failed to parse ${SOURCE_PATH} as JSON: ${err.message}`);
  }

  leafCount = 0;
  const body = renderNode(messages, 0);

  const output =
    [
      "/* eslint-disable */",
      "// AUTO-GENERATED by scripts/gen-i18n-keys.mjs from src/messages/en.json.",
      "// DO NOT EDIT BY HAND. Run `pnpm --filter @hospital/web gen:i18n` to regenerate.",
      "",
      `export const K = ${body} as const;`,
      "",
    ].join("\n");

  await mkdir(dirname(OUTPUT_PATH), { recursive: true });
  await writeFile(OUTPUT_PATH, output, "utf8");

  console.log(
    `Wrote apps/web/src/i18n/keys.generated.ts (${leafCount} leaf keys)`,
  );
}

main().catch((err) => {
  console.error(`gen-i18n-keys failed: ${err.message}`);
  process.exit(1);
});
